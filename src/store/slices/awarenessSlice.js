export const createAwarenessSlice = (set) => ({
  futureSelfNarrative: "",
  // Stores the FULL habit object ({ id, label, source }), not just an id.
  // This is what lets AI-generated habits — which don't exist in
  // habitOptions.mock.json — flow through the rest of the app: nothing
  // downstream needs to look activeHabit up anywhere, it's already
  // complete.
  activeHabit: null,
  habitSelectedAt: null,

  setFutureSelfNarrative: (text) => set({ futureSelfNarrative: text }),

  // habit is the full { id, label, source } object — either one of the
  // curated options from habitOptions.mock.json (source: 'curated') or a
  // new one generated by Gemini from the user's narrative (source: 'ai').
  // The user always makes this choice — the AI only ever suggests, never decides.
  selectHabit: (habit) =>
    set({ activeHabit: habit, habitSelectedAt: new Date().toISOString() }),
});
